# Records every clue id with its current answer (true/false) into tests\snapshot.js.
# The tests then fail if a clue keeps its id but its answer flips (a different claim must get a NEW id,
# because players' saved progress is keyed by id). Run this after intentionally adding clues.
$root = Split-Path -Parent $PSScriptRoot
$pairs = @()
foreach ($t in "animals", "space", "food", "art") {
  $txt = Get-Content (Join-Path $root "data\data-facts-$t.js") -Raw -Encoding UTF8
  foreach ($m in [regex]::Matches($txt, '\{ id: "([a-z]+-\d+)"[^\n]*?answer: (true|false)')) { $pairs += ('"{0}":{1}' -f $m.Groups[1].Value, $m.Groups[2].Value) }
}
$out = "// generated by tests/update-snapshot.ps1 - do not edit by hand`nconst FACT_SNAPSHOT = {" + ($pairs -join ",") + "};`n"
[System.IO.File]::WriteAllText((Join-Path $root "tests\snapshot.js"), $out, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("snapshot: {0} clues" -f $pairs.Count)
